export const guideBySlug = (slug: string) => GUIDES.find((g) => g.slug === slug);

/** 본문 글자 수(공백 제외)로 읽는 시간을 어림한다. 한국어 기준 분당 약 500자. */
export function readingMinutes(g: Guide): number {
  const text = g.sections
    .flatMap((s) => [s.heading, ...s.body.flatMap(blockText)])
    .join("")
    .replace(/\s/g, "");
  return Math.max(1, Math.round(text.length / 500));
}

export function blockText(b: GuideBlock): string[] {
  if (typeof b === "string") return [b];
  if ("list" in b) return b.list;
  if ("note" in b) return [b.note];
  if ("faq" in b) return b.faq.flatMap((f) => [f.q, f.a]);
  return [...b.table.head, ...b.table.rows.flat()];
}
